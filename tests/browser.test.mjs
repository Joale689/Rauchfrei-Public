// Optional: npm install --no-save playwright && npx playwright install chromium
// Start the server first, then: node tests/browser.test.mjs
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
const origin = process.env.TEST_URL || 'http://127.0.0.1:8765/';
const errors=[];
const context = await browser.newContext({timezoneId:'Europe/Berlin', viewport:{width:390,height:844}});
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
page.on('dialog', dialog => dialog.accept());
const key = 'rauchfrei_public_v1:/';
let checks=0;
function pass(message) { checks++; console.log(`PASS ${message}`); }
try {
  await page.goto(origin);
  await page.locator('#begin').click();
  await page.locator('#tracker').waitFor({state:'visible'});
  await page.locator('#cigBtn').click();
  await page.waitForFunction(()=>document.querySelector('#cigCount').textContent==='1');
  await page.locator('#vapeBtn').click();
  await page.waitForFunction(()=>document.querySelector('#vapeCount').textContent==='1');
  await page.reload();
  assert.equal(await page.locator('#cigCount').textContent(),'1');
  pass('Zigarette und Dampfen erfassen; Neuladen erhält Daten');
  await page.locator('#undoBtn').click();
  await page.waitForFunction(()=>document.querySelector('#vapeCount').textContent==='0');
  pass('Rückgängig entfernt den letzten Eintrag');
  await page.getByRole('button',{name:'Uhrzeit ändern'}).click();
  await page.locator('#editDialog').waitFor({state:'visible'});
  // Use a known valid time after recording started by preserving the exact current minute;
  // for the correction test seed older data below instead of moving before onboarding.
  await page.getByRole('button',{name:'Abbrechen',exact:true}).last().click();
  pass('Korrekturdialog lässt sich ohne Datenänderung abbrechen');
  const original = await page.evaluate(k=>localStorage.getItem(k),key);
  await page.evaluate(async () => { await navigator.serviceWorker.ready; await caches.open('unrelated-app-cache'); localStorage.setItem('rauchfrei_v1_events','PRIVATE_SENTINEL'); });
  assert.ok((await page.evaluate(()=>caches.keys())).includes('unrelated-app-cache'));
  await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
  await context.setOffline(true);
  await page.reload();
  await page.locator('#tracker').waitFor({state:'visible'});
  await page.locator('#vapeBtn').click();
  await page.waitForFunction(()=>document.querySelector('#vapeCount').textContent==='1');
  await context.setOffline(false);
  pass('Offline-Neuladen und Erfassen funktionieren');
  const second = await context.newPage();await second.goto(origin);
  await Promise.all([page.locator('#cigBtn').click(),second.locator('#cigBtn').click()]);
  await page.waitForFunction(()=>document.querySelector('#cigCount').textContent==='3');
  assert.equal(await second.locator('#cigCount').textContent(),'3');await second.close();
  pass('Zwei Tabs verlieren bei parallelem Erfassen keine Einträge');
  const saved = await page.evaluate(k=>localStorage.getItem(k),key);
  await page.locator('#importFile').setInputFiles({name:'future.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({app:'Rauchfrei',events:[{type:'cigarette',timestamp:'2099-01-01T00:00:00.000Z'}]}))});
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('Zukunft'));
  assert.equal(await page.evaluate(k=>localStorage.getItem(k),key),saved);
  pass('Zukunftsimport zeigt Fehler und verändert keine Daten');
  await page.locator('#importFile').setInputFiles({name:'restore.json',mimeType:'application/json',buffer:Buffer.from(original)});
  await page.locator('#importDialog').waitFor({state:'visible'});
  await page.getByRole('button',{name:'Import übernehmen',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent==='Backup importiert.');
  assert.equal(await page.evaluate(k=>localStorage.getItem(k+':before-import'),key),saved);
  pass('Bestätigter Import sichert vorherigen Stand');
  const downloadPromise=page.waitForEvent('download');await page.locator('#exportBtn').click();
  const downloaded=await downloadPromise;const exported=JSON.parse(await fs.readFile(await downloaded.path(),'utf8'));
  assert.equal(exported.events.length,1);
  pass('Heruntergeladenes Backup enthält echte gespeicherte Einträge');
  await page.evaluate(async k=>{
    const c=await import('./src/core.js');const now=new Date();const s=c.initialState(new Date(now.getTime()-3*86400000));
    c.addEvent(s,'cigarette',new Date(now.getTime()-30*3600000));
    localStorage.setItem(k,JSON.stringify(s));
  },key);
  await page.reload();
  assert.equal(await page.locator('#cigCount').textContent(),'0');
  assert.notEqual(await page.locator('#sinceLast').textContent(),'Noch keine erfasst');
  await page.getByRole('button',{name:'Vollständig erfasst',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelector('#history').textContent.includes('Vollständigkeits') || document.querySelector('#history').textContent.includes('Erfassung als vollständig bestätigt'));
  pass('Leerer heutiger Tag behält letzte Zigarette; vergangener Tag lässt sich bestätigen');
  await page.locator('#startDayBtn').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.startsWith('Neuer Tag begonnen'));
  assert.equal(await page.locator('#cigCount').textContent(),'0');
  pass('Manueller Tagesbeginn erfasst keine Zigarette');
  await page.locator('#cigBtn').click();
  await page.waitForFunction(()=>document.querySelector('#cigCount').textContent==='1');
  const editStamp=await page.evaluate(()=>{const d=new Date(Date.now()-3600000);const pad=n=>String(n).padStart(2,'0');return `${d.getFullYear()}-${pad(d.getMonth()+1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;});
  await page.getByRole('button',{name:'Uhrzeit ändern'}).click();await page.locator('#editTime').fill(editStamp);
  await page.getByRole('button',{name:'Speichern',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#cigCount').textContent==='0');
  pass('Zeitkorrektur verschiebt den Eintrag in den richtigen vergangenen Tag');
  assert.equal(await page.evaluate(()=>localStorage.getItem('rauchfrei_v1_events')),'PRIVATE_SENTINEL');
  pass('Persönlicher Speicher bleibt unberührt');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await fs.mkdir('test-results',{recursive:true});
  await page.screenshot({path:'test-results/mobile.png',fullPage:true});
  await page.setViewportSize({width:1200,height:1100});
  await page.screenshot({path:'test-results/desktop.png',fullPage:true});
  pass('Mobile Darstellung ohne horizontalen Überlauf; Screenshots erstellt');
  await page.evaluate(k=>localStorage.setItem(k,'{damaged'),key);await page.reload();
  await page.locator('#blocked').waitFor({state:'visible'});
  assert.equal(await page.evaluate(k=>localStorage.getItem(k),key),'{damaged');
  pass('Beschädigter Speicher sperrt Änderungen, ohne Daten zu löschen');
  assert.deepEqual(errors,[]);
  pass('Keine unbehandelten Browserfehler');
  console.log(`${checks} Browserprüfungen bestanden.`);
} finally { await browser.close(); }
